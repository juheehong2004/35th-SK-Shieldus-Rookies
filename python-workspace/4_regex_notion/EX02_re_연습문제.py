import re

'''
**문제 1**  — 로그 문자열 `"[INFO] Service started"`이 `"[ERROR]"`로 시작하는지 `re.match()`로 확인하는 코드를 작성해 봅시다. (시작하지 않으므로 `None`이 반환되는지 확인해보세요.)
'''
log = "[INFO] Service started"

print(re.match(r"\[Error\]", log)) # None




'''
**문제 2** — `text = "요청1: 200, 요청2: 404, 요청3: 500"`에서 `re.findall()`로 3자리 상태 코드를 모두 추출하는 코드를 작성해 봅시다.
'''
text = "요청1: 200, 요청2: 404, 요청3: 500"

codes = re.findall(r"\d{3}", text)

print(codes)




