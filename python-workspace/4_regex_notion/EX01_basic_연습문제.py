import re

'''
**문제 1** — `\d{4}-\d{2}-\d{2}` 패턴이 어떤 형식의 문자열을 검증하는지 설명하고, `"2026-04-05"`라는 문자열이 이 형식을 정확히 만족하는지 `re.match()`로 확인하는 코드를 작성해 봅시다.
'''
str = "2026-04-05"

if re.search(r"\d{4}-\d{2}-\d{2}", str):
    print(f"{str} - '\d{{4}}-\d{{2}}-\d{{2}}' 형식 만족")






'''
**문제 2** — `log_line = "Failed login for admin from 10.0.0.5"`에서 `admin` 또는 `root` 계정이 포함되어 있는지 `re.search()`와 `(admin|root)` 그룹으로 확인하고, 발견되면 경고 메시지를 출력하는 코드를 작성해 봅시다.
'''
log_line = "Failed login for admin from 10.0.0.5"

if re.search(r"(admin|root)", log_line):
    print("[경고] 관리자 계정 접근 발견")






